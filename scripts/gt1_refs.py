#!/usr/bin/env python3
"""Regenerate ``src/pygoattracker/_gt1_builds.py``: facts, not code, about each
GoatTracker V1.x playroutine build (``gt1.analyse``: label offsets, relocation
targets, wild offsets, digests), from assembled references outside the tree.

``--refs REV`` reads them from the ``_gt1_refs.py`` module at a git revision;
``--check`` exits 1 when the facts module is stale.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

import black

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "src"))

from pygoattracker.gt1 import analyse  # noqa: E402

OUT = REPO / "src" / "pygoattracker" / "_gt1_builds.py"
REFS = "2282cf3"


def references(rev: str) -> dict:
    """The ``PLAYERS`` of ``_gt1_refs.py`` at git revision ``rev``."""
    text = subprocess.run(
        ["git", "-C", str(REPO), "show", f"{rev}:src/pygoattracker/_gt1_refs.py"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    scope: dict = {}
    exec(compile(text, "_gt1_refs", "exec"), scope)  # pylint: disable=exec-used
    return scope["PLAYERS"]


def build(rev: str) -> str:
    """Render the facts module from the references at ``rev``."""
    facts = {
        name: analyse(name, ref["family"], ref["code"], ref["labels"], ref["author"])
        for name, ref in references(rev).items()
    }
    text = (
        '"""Facts about each GoatTracker V1.x playroutine build (generated by\n'
        'scripts/gt1_refs.py; see ``pygoattracker.gt1.analyse``)."""\n\n'
        f"PLAYERS = {facts!r}\n"
    )
    return black.format_str(text, mode=black.Mode())


def main(argv=None) -> int:
    """CLI entry point."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--refs", default=REFS, help="git revision of the references")
    parser.add_argument("--check", action="store_true", help="only compare")
    args = parser.parse_args(argv)
    text = build(args.refs)
    if args.check:
        if OUT.read_text() != text:
            print(f"{OUT} is stale; rerun scripts/gt1_refs.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
